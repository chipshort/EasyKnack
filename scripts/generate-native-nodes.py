#!/usr/bin/env python3
"""Portable native node-registry generator.

Mirrors scripts/generate-native-nodes.ps1: every EASYKNACK_NODE(Type, "id")
declaration under the node directory produces a registry entry and a nodes.json
manifest. Content is only rewritten when it changed.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

DECLARATION = re.compile(
    r'(?m)^\s*EASYKNACK_NODE\(\s*([A-Za-z_][A-Za-z0-9_:]*)\s*,\s*"([a-z][a-z0-9_-]*)"\s*\)\s*$'
)
MACRO_START = re.compile(r"(?m)^\s*EASYKNACK_NODE")


def project_root() -> Path:
    return Path(__file__).resolve().parent.parent


def discover(node_directory: Path) -> list[dict[str, str]]:
    registrations: list[dict[str, str]] = []
    ids: set[str] = set()
    for header in sorted(node_directory.rglob("*.hpp"), key=lambda path: path.as_posix()):
        text = header.read_text(encoding="utf-8")
        declarations = DECLARATION.findall(text)
        for node_type, node_id in declarations:
            if node_id in ids:
                raise ValueError(f"Duplicate native processor ID: {node_id}")
            ids.add(node_id)
            relative = header.relative_to(node_directory).as_posix()
            registrations.append({"id": node_id, "type": node_type, "header": f"nodes/{relative}"})
        if len(MACRO_START.findall(text)) != len(declarations):
            raise ValueError(f"Malformed EASYKNACK_NODE in {header.name}")
    if not registrations:
        raise ValueError("No native node registrations found")
    return registrations


def render_registry(registrations: list[dict[str, str]]) -> str:
    lines = [
        "// Generated by generate-native-nodes.ps1. Do not edit.",
        "#pragma once",
        "#include <memory>",
        "#include <string>",
        "#include <stdexcept>",
    ]
    seen: set[str] = set()
    for registration in registrations:
        header = registration["header"]
        if header not in seen:
            seen.add(header)
            lines.append(f'#include "{header}"')
    lines.extend(
        [
            "namespace easyknack {",
            "inline std::unique_ptr<NodeProcessor> createNodeProcessor(const std::string& id) {",
        ]
    )
    for registration in registrations:
        lines.append(
            f'    if (id == "{registration["id"]}") return std::make_unique<{registration["type"]}>();'
        )
    lines.extend(
        [
            '    throw std::runtime_error("unknown node type: " + id);',
            "}",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


def render_manifest(registrations: list[dict[str, str]]) -> str:
    return json.dumps(registrations, indent=4, ensure_ascii=False) + "\n"


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    encoded = content.encode("utf-8")
    if path.is_file() and path.read_bytes() == encoded:
        return
    path.write_bytes(encoded)


def main() -> int:
    root = project_root()
    parser = argparse.ArgumentParser(description="Generate the EasyKnack native node registry.")
    parser.add_argument(
        "--node-directory",
        type=Path,
        default=root / "native/audio-host/src/nodes",
        help="directory scanned recursively for *.hpp registrations",
    )
    parser.add_argument(
        "--output-directory",
        type=Path,
        default=root / "target/native/generated",
        help="directory receiving GeneratedNodeRegistry.hpp and nodes.json",
    )
    arguments = parser.parse_args()
    try:
        registrations = discover(arguments.node_directory)
        write_if_changed(arguments.output_directory / "GeneratedNodeRegistry.hpp", render_registry(registrations))
        write_if_changed(arguments.output_directory / "nodes.json", render_manifest(registrations))
    except (OSError, UnicodeError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
